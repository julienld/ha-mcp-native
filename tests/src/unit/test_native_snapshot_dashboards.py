@pytest.fixture
def dashboard_history(runtime, dashboards):
    manager, snapshots, store, *_ = runtime
    storage, owner, collection, active, _module = dashboards
    manager.hass.data = storage.hass.data
    manager.hass.config.recovery_mode = False
    manager.backend.authorize = storage.authorize
    saved = {
        "dashboard": {**owner.config, "title": "Saved title"},
        "config": {"views": [{"path": "home", "title": "Saved view"}]},
    }
    path = store.capture("dashboard", "my-dash", saved, "fixture")
    return snapshots, store, path, owner, collection, active


async def test_dashboard_restore_keeps_settings_body_and_one_safety_image(
    dashboard_history,
):
    snapshots, store, path, owner, collection, _active = dashboard_history
    expected = {
        "dashboard": copy.deepcopy(owner.config),
        "config": copy.deepcopy(owner._data["config"]),
    }
    data, current = await snapshots.snapshot_comparison(path.name, CallContext("owner"))
    assert data["kind"] == "dashboard_settings" and current == expected
    result = await asyncio.wait_for(
        snapshots.restore_snapshot(path.name, CallContext("owner")), 2
    )
    assert result["apply_status"] == "applied"
    assert owner._data["config"]["views"][0]["title"] == "Saved view"
    assert collection.data["my_dash"]["title"] == "Saved title"
    assert store.read_snapshot(result["safety_backup"])["config"] == expected
    assert len(store.list_snapshots(domain="dashboard")) == 2


@pytest.mark.parametrize("change", ["owner", "body", "revoke"])
async def test_dashboard_restore_checks_pinned_owner_after_safety_io(
    dashboard_history, monkeypatch, change
):
    snapshots, _store, path, owner, collection, active = dashboard_history
    io = snapshots._io

    async def changed(function, *args):
        result = await io(function, *args)
        if function.__name__ == "capture":
            if change == "owner":
                collection.dashboards["my-dash"] = LovelaceStorage(
                    copy.deepcopy(owner.config), owner._data["config"]
                )
            elif change == "body":
                owner._data["config"] = {"views": [{"title": "Concurrent"}]}
            else:
                active[0] = False
        return result

    monkeypatch.setattr(snapshots, "_io", changed)
    with pytest.raises(BackupRestoreError) as error:
        await snapshots.restore_snapshot(path.name, CallContext("owner"))
    assert error.value.outcome["apply_status"] == "not_applied" and not owner.calls


async def test_deleted_dashboard_is_recreated_from_saved_settings_and_body(
    dashboard_history,
):
    snapshots, _store, path, _owner, collection, _active = dashboard_history
    await collection.async_delete_item("my_dash")
    result = await snapshots.restore_snapshot(path.name, CallContext("owner"))
    recreated = collection.dashboards["my-dash"]
    assert result["apply_status"] == "applied" and result["safety_backup"] is None
    assert (
        recreated.config["title"] == "Saved title"
        and recreated._data["config"]["views"][0]["title"] == "Saved view"
    )
    await snapshots.restore_snapshot(path.name, CallContext("owner"))
    assert collection.dashboards["my-dash"] is recreated and len(collection.data) == 1


async def test_old_body_only_dashboard_snapshot_changes_no_metadata(dashboard_history):
    snapshots, _store, path, owner, collection, _active = dashboard_history
    data = yaml.safe_load(path.read_text())
    data.pop("kind")
    data["config"] = data["config"]["config"]
    path.write_text(yaml.safe_dump(data), encoding="utf-8")
    _, current = await snapshots.snapshot_comparison(path.name, CallContext("owner"))
    assert current == owner._data["config"]
    result = await snapshots.restore_snapshot(path.name, CallContext("owner"))
    assert (
        result["apply_status"] == "applied"
        and collection.data["my_dash"]["title"] == "Before"
    )


