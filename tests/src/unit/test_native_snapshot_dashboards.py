async def test_dashboard_restore_cannot_rebase_away_from_its_supplied_safety_image(
    dashboard_history,
):
    snapshots, store, path, owner, _collection, _active = dashboard_history
    restore = snapshots.domains.dashboard_restore(
        store.read_snapshot(path.name), CallContext("owner")
    )
    before = await restore.current()
    owner._data["config"] = {"views": [{"title": "Concurrent"}]}
    await restore.current()
    with pytest.raises(ToolFailure) as error:
        await restore.apply(before)
    assert error.value.code == "CONFIG_CONFLICT"
    assert error.value.status == "not_started" and not owner.calls


async def test_dashboard_restore_reports_divergent_body_without_updating_settings(
    dashboard_history,
):
    snapshots, _store, path, owner, _collection, _active = dashboard_history
    owner.release = asyncio.Event()
    restore = asyncio.create_task(
        snapshots.restore_snapshot(path.name, CallContext("owner"))
    )
    other = None
    try:
        await asyncio.wait_for(owner.loaded.wait(), 2)
        other = asyncio.create_task(
            owner.async_save({"views": [{"title": "Concurrent"}]})
        )
        await asyncio.sleep(0)
        owner.release.set()
        with pytest.raises(BackupRestoreError) as error:
            _ = await restore
    finally:
        owner.release.set()
        await asyncio.gather(
            *([restore, other] if other is not None else [restore]),
            return_exceptions=True,
        )
    assert error.value.outcome["apply_status"] == "unknown"
    assert error.value.outcome["reason"] == "verification_failed"
    assert error.value.outcome["config_applied"] is True
    assert (
        owner.config["title"] == "Before"
        and owner._data["config"]["views"][0]["title"] == "Concurrent"
    )


async def test_dashboard_clear_restore_verifies_absence_before_writing_metadata(
    dashboard_history, monkeypatch
):
    snapshots, store, _path, owner, _collection, _active = dashboard_history
    path = store.capture(
        "dashboard",
        "my-dash",
        {"dashboard": {**owner.config, "title": "Saved metadata"}, "config": None},
        "fixture",
        force=True,
    )
    started, release = asyncio.Event(), asyncio.Event()

    async def deleting():
        owner._data = {"config": None}
        owner.calls.append(None)
        started.set()
        await release.wait()

    monkeypatch.setattr(owner, "async_delete", deleting)
    task = asyncio.create_task(
        snapshots.restore_snapshot(path.name, CallContext("owner"))
    )
    try:
        await asyncio.wait_for(started.wait(), 2)
        await owner.async_save({"views": [{"title": "Concurrent"}]})
        release.set()
        with pytest.raises(BackupRestoreError) as error:
            _ = await task
    finally:
        release.set()
        await asyncio.gather(task, return_exceptions=True)
    assert error.value.outcome["reason"] == "verification_failed"
    assert error.value.outcome["apply_status"] == "unknown"
    assert (
        owner.config["title"] == "Before"
        and owner._data["config"]["views"][0]["title"] == "Concurrent"
    )
